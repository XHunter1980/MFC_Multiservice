# -*- coding: utf-8 -*-
"""
Единый источник версии приложения «МФК Мультисервис».

ВАЖНО (контракт релизной автоматизации):
  Значение APP_VERSION должно всегда совпадать с версией, зашитой в исходном
  коде приложения (константа UpdaterApp.VERSION_INFO в файле MFC_Multiservice_*.py).

При изменении версии в исходнике:
  1. Обновите APP_VERSION в этом файле.
  2. Создайте тег вида v<APP_VERSION> (например v9.6) — GitHub Actions
     соберёт Windows EXE и опубликует релиз с этим номером версии.

Скрипты CI (.github/scripts/get_version.py) и сборщик (build.spec) читают
версию именно отсюда. Исходный код приложения этот файл не использует.
"""

APP_VERSION = "9.6"


def get_version() -> str:
    """Возвращает текущую версию приложения (строка, без префикса 'v')."""
    return APP_VERSION


if __name__ == "__main__":
    print(APP_VERSION)
